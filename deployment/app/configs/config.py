"""Centralized application configuration and path resolution.

The deployment service reads configuration from environment variables while
deriving stable filesystem paths from the project root. Keeping path and service
settings in one class prevents model loading, storage, database, and Kafka code
from duplicating environment parsing logic.
"""

import os
from urllib.parse import quote_plus
from pathlib import Path


class AppConfig:
    """Environment-backed settings for API, inference, storage, and integrations.

    The class is intentionally static because the service reads configuration at
    import/startup time and shares those values across model loading, request
    handling, persistence, Kafka, MLflow, and Hugging Face integration code.
    Keeping the settings here makes deployment differences explicit while
    preserving stable paths for local development.
    """

    # Base paths are derived instead of hard-coded so the app works from local
    # Python runs, Docker containers, and CI without changing source code.
    ROOT_DIR = Path(__file__).resolve().parent.parent.parent

    # Top-level project directories. These form the shared contract between the
    # API, static frontend, generated prediction artifacts, and model artifacts.
    APP_DIR = ROOT_DIR / "app"
    ASSETS_DIR = ROOT_DIR / "assets"
    FRONTEND_DIR = ROOT_DIR / "frontend"
    MODELS_ROOT = ROOT_DIR / "saved_models"

    # Model categories mirror the release layout generated by the MLOps layer.
    # Keeping this structure explicit makes missing or misplaced artifacts easy
    # to diagnose during startup checks.
    CLASSIFICATION_DIR = MODELS_ROOT / "healthy_unhealthy"
    DISEASES_DIR = MODELS_ROOT / "diseases"
    SEGMENTATION_DIR = MODELS_ROOT / "segmentation"

    # Binary healthy/unhealthy ensemble members. Each directory is expected to
    # contain metadata plus the runtime artifact selected by MODEL_RUNTIME.
    DENSENET_PATH = CLASSIFICATION_DIR / "densenet"
    EFFICIENTNET_PATH = CLASSIFICATION_DIR / "efficientnet"
    INCEPTION_PATH = CLASSIFICATION_DIR / "inception"
    MOBILENET_PATH = CLASSIFICATION_DIR / "mobilenet"

    # Disease subtyping currently uses one DenseNet model behind the binary
    # ensemble gate, so the runtime only needs this single diseases directory.
    DISEASE_DENSENET_PATH = DISEASES_DIR / "densenet"

    # Segmentation produces both the visible mask artifact and the lung ROI used
    # by disease classification.
    UNET_PATH = SEGMENTATION_DIR / "unet_xception"

    # Mapping and artifact paths are part of the API contract: labels and image
    # links returned to clients should remain stable across runtime backends.
    CLASSIFICATION_JSON = ASSETS_DIR / "healthy_unhealthy_mapping.json"
    DISEASES_JSON = ASSETS_DIR / "diseases_mapping.json"
    PREDICTION_DIR = ASSETS_DIR / "predictions"
    PREDICTION_STORAGE_BACKEND = os.getenv("PREDICTION_STORAGE_BACKEND", "local").lower()
    PREDICTION_PUBLIC_BASE_URL = os.getenv(
        "PREDICTION_PUBLIC_BASE_URL",
        "/static/predictions",
    ).rstrip("/")
    SUPABASE_URL = os.getenv("SUPABASE_URL", "").rstrip("/")
    SUPABASE_SERVICE_ROLE_KEY = os.getenv("SUPABASE_SERVICE_ROLE_KEY", "")
    SUPABASE_STORAGE_BUCKET = os.getenv(
        "SUPABASE_STORAGE_BUCKET",
        "lung-detection-predictions",
    )
    SUPABASE_SIGNED_URL_EXPIRES_SECONDS = int(
        os.getenv("SUPABASE_SIGNED_URL_EXPIRES_SECONDS", "3600")
    )

    # Global inference and integration settings. Environment variables let the
    # same source tree run as a local app, Docker Compose stack, or cloud service.
    IMAGE_SIZE = (256, 256)
    MODEL_RUNTIME = os.getenv("MODEL_RUNTIME", "onnx").lower()
    CORS_ALLOW_ORIGINS = [
        origin.strip()
        for origin in os.getenv("CORS_ALLOW_ORIGINS", "").split(",")
        if origin.strip()
    ]
    DB_HOST = os.getenv("DB_HOST", "localhost")
    DB_PORT = os.getenv("DB_PORT", "1433")
    DB_NAME = os.getenv("DB_NAME", "lung_detection")
    DB_USER = os.getenv("DB_USER", "sa")
    DB_PASSWORD = os.getenv("DB_PASSWORD", "")
    DB_DRIVER = os.getenv("DB_DRIVER", "ODBC Driver 18 for SQL Server")
    DB_ENCRYPT = os.getenv("DB_ENCRYPT", "yes")
    DB_TRUST_SERVER_CERTIFICATE = os.getenv("DB_TRUST_SERVER_CERTIFICATE", "yes")
    DB_ECHO = os.getenv("DB_ECHO", "false").lower() == "true"
    DB_LOGGING_ENABLED = os.getenv("DB_LOGGING_ENABLED", "true").lower() == "true"
    # Database backend: "mssql" (default, local full stack) or "postgres" (cloud deploy).
    DB_BACKEND = os.getenv("DB_BACKEND", "mssql").lower()
    # Full SQLAlchemy URL. When set it takes precedence over the discrete DB_* vars.
    # Render/Railway inject this automatically for their managed Postgres.
    DATABASE_URL = os.getenv("DATABASE_URL", "")
    # Optional Postgres TLS mode (managed Postgres usually needs "require").
    DB_SSLMODE = os.getenv("DB_SSLMODE", "")
    LOGS_API_KEY = os.getenv("LOGS_API_KEY", "")
    KAFKA_ENABLED = os.getenv("KAFKA_ENABLED", "true").lower() == "true"
    KAFKA_BOOTSTRAP_SERVERS = os.getenv("KAFKA_BOOTSTRAP_SERVERS", "127.0.0.1:9092")
    KAFKA_TOPIC_PREDICTIONS = os.getenv("KAFKA_TOPIC_PREDICTIONS", "lung.predictions")
    KAFKA_CLIENT_ID = os.getenv("KAFKA_CLIENT_ID", "lung-api-producer")
    KAFKA_SECURITY_PROTOCOL = os.getenv("KAFKA_SECURITY_PROTOCOL", "PLAINTEXT")
    KAFKA_SASL_MECHANISM = os.getenv("KAFKA_SASL_MECHANISM", "")
    KAFKA_SASL_USERNAME = os.getenv("KAFKA_SASL_USERNAME", "")
