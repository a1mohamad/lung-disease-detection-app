    @staticmethod
    def get_metadata_path(model_dir: Path) -> Path:
        """Return the metadata file path for a model artifact directory.

        Args:
            model_dir: Directory containing a model runtime artifact and its
                ``metadata.yaml`` contract.

        Returns:
            Path to the metadata file expected by startup and model loaders.
        """
        return model_dir / "metadata.yaml"

    @staticmethod
    def get_database_url() -> str:
        """Resolve the SQLAlchemy database URL for the configured backend.

        Explicit ``DATABASE_URL`` values win because managed cloud databases
        usually inject a complete connection string. When it is absent, the URL
        is assembled from discrete ``DB_*`` variables for local Compose stacks.

        Returns:
            SQLAlchemy-compatible database URL.
        """
        # Explicit full URL wins (12-factor; Render/Railway inject DATABASE_URL).
        if AppConfig.DATABASE_URL:
            return AppConfig._normalize_database_url(AppConfig.DATABASE_URL)

        # Discrete vars are useful for Docker Compose and local development.
        if AppConfig.DB_BACKEND == "postgres":
            return AppConfig._build_postgres_url()

        # Default: SQL Server, preserving the original local full-stack setup.
        return AppConfig._build_mssql_url()

    @staticmethod
    def _normalize_database_url(url: str) -> str:
        """Normalize provider Postgres URLs to the psycopg2 SQLAlchemy dialect.

        Args:
            url: Raw database URL supplied by the environment.

        Returns:
            URL with an explicit SQLAlchemy driver when the provider uses a bare
            Postgres scheme.
        """
        # Normalize the bare schemes some providers emit so SQLAlchemy uses psycopg2.
        if url.startswith("postgres://"):
            return "postgresql+psycopg2://" + url[len("postgres://"):]
        if url.startswith("postgresql://"):
            return "postgresql+psycopg2://" + url[len("postgresql://"):]
        return url

    @staticmethod
    def _build_postgres_url() -> str:
        """Build a Postgres SQLAlchemy URL from discrete environment variables.

        Returns:
            SQLAlchemy URL using ``postgresql+psycopg2`` and optional SSL mode.
        """
        user = quote_plus(AppConfig.DB_USER)
        password = quote_plus(AppConfig.DB_PASSWORD)
        host = AppConfig.DB_HOST
        port = AppConfig.DB_PORT.strip() if AppConfig.DB_PORT else ""
        # Fall back to the Postgres default port when unset or left at the MSSQL default.
        if port in ("", "1433"):
            port = "5432"

        url = f"postgresql+psycopg2://{user}:{password}@{host}:{port}/{AppConfig.DB_NAME}"
        if AppConfig.DB_SSLMODE:
            url += f"?sslmode={AppConfig.DB_SSLMODE}"
        return url

    @staticmethod
    def _build_mssql_url() -> str:
        """Build a SQL Server SQLAlchemy URL from discrete environment variables.

        Returns:
            SQLAlchemy URL using ``mssql+pyodbc`` with encryption and trust
            options carried through to the ODBC driver.
        """
        user = quote_plus(AppConfig.DB_USER)
        password = quote_plus(AppConfig.DB_PASSWORD)
        driver = quote_plus(AppConfig.DB_DRIVER)
        host = AppConfig.DB_HOST
        port = AppConfig.DB_PORT.strip() if AppConfig.DB_PORT else ""

        server = host
        if port and "\\" not in host:
            server = f"{host}:{port}"

        return (
            f"mssql+pyodbc://{user}:{password}@{server}/{AppConfig.DB_NAME}"
            f"?driver={driver}"
            f"&Encrypt={AppConfig.DB_ENCRYPT}"
            f"&TrustServerCertificate={AppConfig.DB_TRUST_SERVER_CERTIFICATE}"
        )
